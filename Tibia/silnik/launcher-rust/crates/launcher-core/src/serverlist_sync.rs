//! LR-025: Synchronizacja listy serwerów z manifestu do plików klienta.
//!
//! Launcher aktualizuje plik listy serwerów klienta na podstawie
//! danych z manifestu (servers[]). Gracz nie edytuje listy ręcznie —
//! wybór świata odbywa się w kliencie.

use std::fs;
use std::path::Path;

use common_models::manifest::ServerEntryRaw;

/// Błędy synchronizacji listy serwerów.
#[derive(Debug, thiserror::Error)]
pub enum ServerlistError {
    #[error("I/O error ({context}): {source}")]
    IoError {
        context: String,
        #[source]
        source: std::io::Error,
    },

    #[error("No servers to sync")]
    NoServers,
}

/// Synchronizuje listę serwerów do pliku Lua klienta.
///
/// Generuje plik `init_serverlist.lua` (lub inny konfigurowalny)
/// z tabelą serwerów do użycia przez klienta OTClient.
pub fn sync_serverlist(
    servers: &[ServerEntryRaw],
    output_path: &Path,
) -> Result<(), ServerlistError> {
    if servers.is_empty() {
        tracing::warn!("Brak serwerów do synchronizacji w manifeście");
        return Ok(()); // Nie błąd krytyczny — manifest może nie mieć serwerów
    }

    let lua_content = generate_serverlist_lua(servers);

    if let Some(parent) = output_path.parent() {
        fs::create_dir_all(parent).map_err(|e| ServerlistError::IoError {
            context: "create serverlist dir".into(),
            source: e,
        })?;
    }

    // Atomowy zapis: tmp → rename
    let tmp_path = output_path.with_extension("lua.tmp");

    fs::write(&tmp_path, lua_content.as_bytes()).map_err(|e| ServerlistError::IoError {
        context: "write serverlist tmp".into(),
        source: e,
    })?;

    fs::rename(&tmp_path, output_path).map_err(|e| ServerlistError::IoError {
        context: "rename serverlist".into(),
        source: e,
    })?;

    tracing::info!(
        "Zsynchronizowano {} serwerów do {}",
        servers.len(),
        output_path.display()
    );

    Ok(())
}

/// Generuje zawartość pliku Lua z listą serwerów.
fn generate_serverlist_lua(servers: &[ServerEntryRaw]) -> String {
    let mut lua = String::new();
    lua.push_str("-- Wygenerowane automatycznie przez launcher. Nie edytuj ręcznie.\n");
    lua.push_str("-- Auto-generated by launcher. Do not edit manually.\n\n");
    lua.push_str("MANAGED_SERVER_LIST = {\n");

    for server in servers {
        if !server.visible || !server.enabled {
            continue;
        }

        lua.push_str("  {\n");
        lua.push_str(&format!("    id = \"{}\",\n", escape_lua(&server.id)));
        lua.push_str(&format!("    name = \"{}\",\n", escape_lua(&server.name)));
        lua.push_str(&format!("    host = \"{}\",\n", escape_lua(&server.host)));
        lua.push_str(&format!("    port = {},\n", server.port));

        if let Some(ref mode) = server.game_mode {
            lua.push_str(&format!("    gameMode = \"{}\",\n", escape_lua(mode)));
        }

        lua.push_str(&format!("    priority = {},\n", server.priority));

        if let Some(ref channel) = server.channel {
            lua.push_str(&format!("    channel = \"{}\",\n", escape_lua(channel)));
        }

        lua.push_str("  },\n");
    }

    lua.push_str("}\n");
    lua
}

/// Escape string for Lua string literal.
fn escape_lua(s: &str) -> String {
    s.replace('\\', "\\\\")
        .replace('"', "\\\"")
        .replace('\n', "\\n")
        .replace('\r', "\\r")
        .replace('\0', "")
}

/// Generuje listę serwerów w formacie JSON (alternatywny format).
pub fn sync_serverlist_json(
    servers: &[ServerEntryRaw],
    output_path: &Path,
) -> Result<(), ServerlistError> {
    if servers.is_empty() {
        return Ok(());
    }

    let json =
        serde_json::to_string_pretty(servers).unwrap_or_else(|_| "[]".to_string());

    if let Some(parent) = output_path.parent() {
        fs::create_dir_all(parent).map_err(|e| ServerlistError::IoError {
            context: "create serverlist dir".into(),
            source: e,
        })?;
    }

    let tmp_path = output_path.with_extension("json.tmp");
    fs::write(&tmp_path, json.as_bytes()).map_err(|e| ServerlistError::IoError {
        context: "write serverlist json tmp".into(),
        source: e,
    })?;

    fs::rename(&tmp_path, output_path).map_err(|e| ServerlistError::IoError {
        context: "rename serverlist json".into(),
        source: e,
    })?;

    Ok(())
}

