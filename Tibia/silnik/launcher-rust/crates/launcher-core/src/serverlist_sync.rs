#[cfg(test)]
mod tests {
    use super::*;

    fn sample_servers() -> Vec<ServerEntryRaw> {
        vec![
            ServerEntryRaw {
                id: "classic74-main".to_string(),
                name: "Classic 7.4".to_string(),
                host: "classic.example.com".to_string(),
                port: 7171,
                game_mode: Some("classic74".to_string()),
                visible: true,
                enabled: true,
                priority: 10,
                channel: Some("stable".to_string()),
            },
            ServerEntryRaw {
                id: "modern-main".to_string(),
                name: "Modern".to_string(),
                host: "modern.example.com".to_string(),
                port: 7171,
                game_mode: Some("modern".to_string()),
                visible: true,
                enabled: true,
                priority: 20,
                channel: None,
            },
            ServerEntryRaw {
                id: "hidden-test".to_string(),
                name: "Hidden Test".to_string(),
                host: "test.example.com".to_string(),
                port: 7172,
                game_mode: None,
                visible: false,
                enabled: true,
                priority: 100,
                channel: Some("test".to_string()),
            },
        ]
    }

    #[test]
    fn test_generate_lua() {
        let servers = sample_servers();
        let lua = generate_serverlist_lua(&servers);

        assert!(lua.contains("MANAGED_SERVER_LIST"));
        assert!(lua.contains("classic.example.com"));
        assert!(lua.contains("modern.example.com"));
        // Ukryty serwer nie powinien być w wyjściu
        assert!(!lua.contains("test.example.com"));
    }

    #[test]
    fn test_sync_serverlist_to_file() {
        let tmp = tempfile::tempdir().expect("tmpdir");
        let output = tmp.path().join("data/serverlist.lua");

        let servers = sample_servers();
        sync_serverlist(&servers, &output).expect("sync");

        assert!(output.exists());
        let content = std::fs::read_to_string(&output).expect("read");
        assert!(content.contains("Classic 7.4"));
        assert!(content.contains("Modern"));
    }

    #[test]
    fn test_sync_empty_servers() {
        let tmp = tempfile::tempdir().expect("tmpdir");
        let output = tmp.path().join("serverlist.lua");

        let result = sync_serverlist(&[], &output);
        assert!(result.is_ok());
        // Plik nie powinien zostać utworzony (brak serwerów)
        assert!(!output.exists());
    }

    #[test]
    fn test_escape_lua() {
        assert_eq!(escape_lua("normal"), "normal");
        assert_eq!(escape_lua("with\"quotes"), "with\\\"quotes");
        assert_eq!(escape_lua("back\\slash"), "back\\\\slash");
        assert_eq!(escape_lua("new\nline"), "new\\nline");
    }

    #[test]
    fn test_sync_serverlist_json() {
        let tmp = tempfile::tempdir().expect("tmpdir");
        let output = tmp.path().join("servers.json");

        let servers = sample_servers();
        sync_serverlist_json(&servers, &output).expect("sync json");

        assert!(output.exists());
        let content = std::fs::read_to_string(&output).expect("read");
        assert!(content.contains("classic74-main"));
    }
}
