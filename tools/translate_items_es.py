def translate_suffix_smart(prefix_text, suffix_en, suffix_es):
    """
    Inteligentne tłumaczenie wzorca "X suffix" z uwzględnieniem gramatyki.
    Jeśli prefix to pojedynczy przymiotnik → suffix_es + adj_es (z uzgodnieniem rodzaju)
    Jeśli prefix to materiał/rzeczownik → suffix_es de mod_es
    """
    prefix_words = prefix_text.strip().split()

    # Single adjective prefix → "suffix_es adj_es" with gender agreement
    if len(prefix_words) == 1:
        word = prefix_words[0].lower()
        if is_adjective(word):
            adj_es = WORD_DICT.get(word, word)
            adj_es = agree_adjective(adj_es, suffix_es)
            return f"{suffix_es} {adj_es}"

    # Multi-word prefix where first word is adjective and second is noun/material
    # e.g. "dark stone door" → "puerta de piedra oscura"
    if len(prefix_words) == 2:
        w0, w1 = [w.lower() for w in prefix_words]
        if is_adjective(w0) and (is_noun(w1) or w1 in WORD_DICT):
            mod_es = WORD_DICT.get(w1, prefix_words[1])
            adj_es = WORD_DICT.get(w0, prefix_words[0])
            adj_es = agree_adjective(adj_es, suffix_es)
            return f"{suffix_es} {adj_es} de {mod_es}"

    # Default: treat prefix as material/type modifier → suffix_es de mod_es
    mod = translate_compound(prefix_text)
    return f"{suffix_es} de {mod}"


