def agree_adjective(adj_es, noun_es):
    """
    Aplica concordancia de género al adjetivo español.
    Si el sustantivo es femenino, cambia -o → -a en el adjetivo.
    """
    if not adj_es or not noun_es:
        return adj_es

    # Sprawdź czy rzeczownik jest żeński
    noun_base = noun_es.lower().strip()
    is_fem = noun_base in FEMININE_NOUNS_ES

    if not is_fem:
        return adj_es

    # Adjectives ending in -o → -a for feminine
    if adj_es.endswith('o'):
        return adj_es[:-1] + 'a'
    # Adjectives ending in -ón → -ona
    if adj_es.endswith('ón'):
        return adj_es + 'a'
    # Most other adjectives are invariable (e.g., -e, -l, -r, -z, -s)
    return adj_es


def translate_compound(text):
    """
    Tłumaczy złożoną nazwę z poprawną kolejnością słów hiszpańskich.
    W hiszpańskim: rzeczownik + przymiotnik (np. "espada mágica", nie "mágica espada")
    Złożone: "X Y" gdzie X modyfikuje Y → "Y de X" (np. "orc tooth" → "diente de orco")
    """
    text = text.strip()
    if not text:
        return text

    # Check exact match first
    text_lower = text.lower()
    if text_lower in EXACT_TRANSLATIONS:
        return EXACT_TRANSLATIONS[text_lower]

    words = text.split()
    if len(words) == 1:
        word = text_lower
        if word in WORD_DICT and WORD_DICT[word]:
            return WORD_DICT[word]
        return text

    # --- Two-word compound: ADJ + NOUN → NOUN_es + ADJ_es ---
    if len(words) == 2:
        w0 = words[0].lower()
        w1 = words[1].lower()

        # Try 2-word exact match
        two_word = f"{w0} {w1}"
        if two_word in EXACT_TRANSLATIONS:
            return EXACT_TRANSLATIONS[two_word]

        # ADJ + NOUN → NOUN_es ADJ_es (with gender agreement)
        if is_adjective(w0) and is_noun(w1):
            noun_es = WORD_DICT.get(w1, words[1])
            adj_es = WORD_DICT.get(w0, words[0])
            if noun_es and adj_es:
                adj_es = agree_adjective(adj_es, noun_es)
                return f"{noun_es} {adj_es}"

        # NOUN + NOUN (modifier + head) → head_es de mod_es
        # (e.g. "orc tooth" → "diente de orco", "dragon scale" → "escama de dragón")
        if is_noun(w0) and is_noun(w1):
            head_es = WORD_DICT.get(w1, words[1])
            mod_es = WORD_DICT.get(w0, words[0])
            if head_es and mod_es:
                return f"{head_es} de {mod_es}"

        # NOUN + ADJ → Already correct order, just translate (with gender)
        if is_noun(w0) and is_adjective(w1):
            noun_es = WORD_DICT.get(w0, words[0])
            adj_es = WORD_DICT.get(w1, words[1])
            if noun_es and adj_es:
                adj_es = agree_adjective(adj_es, noun_es)
                return f"{noun_es} {adj_es}"

        # Material/creature + item (e.g. "amber bow", "coconut shoes")
        if w0 in WORD_DICT and is_noun(w1):
            mod_es = WORD_DICT.get(w0, words[0])
            head_es = WORD_DICT.get(w1, words[1])
            if head_es:
                return f"{head_es} de {mod_es}"

        # ADJ + unknown noun (apply as-is, no gender since unknown)
        if is_adjective(w0) and w0 in WORD_DICT:
            adj_es = WORD_DICT[w0]
            return f"{words[1]} {adj_es}"

        # Unknown modifier + known NOUN → noun de modifier
        if is_noun(w1) and w1 in WORD_DICT:
            noun_es = WORD_DICT[w1]
            return f"{noun_es} de {words[0]}"

        # Known word + unknown → try "unknown de known" if first is material-like
        if w0 in WORD_DICT and w0 not in ("a", "an", "the", "of", "with", "for", "from", "in", "on", "at", "to", "and", "or"):
            mod_es = WORD_DICT[w0]
            return f"{words[1]} de {mod_es}"

    # --- Three-word compound ---
    if len(words) == 3:
        w0, w1, w2 = [w.lower() for w in words]

        # Try 3-word exact match
        three_word = f"{w0} {w1} {w2}"
        if three_word in EXACT_TRANSLATIONS:
            return EXACT_TRANSLATIONS[three_word]

        # ADJ + ADJ + NOUN → NOUN_es ADJ_es ADJ_es
        if is_adjective(w0) and is_adjective(w1) and is_noun(w2):
            n = WORD_DICT.get(w2, words[2])
            a0 = WORD_DICT.get(w0, words[0])
            a1 = WORD_DICT.get(w1, words[1])
            a0 = agree_adjective(a0, n)
            a1 = agree_adjective(a1, n)
            return f"{n} {a0} {a1}"

        # ADJ + NOUN + NOUN → NOUN2 de NOUN1 ADJ
        if is_adjective(w0) and is_noun(w1) and is_noun(w2):
            n = WORD_DICT.get(w2, words[2])
            mod = WORD_DICT.get(w1, words[1])
            adj = WORD_DICT.get(w0, words[0])
            adj = agree_adjective(adj, n)
            return f"{n} {adj} de {mod}"

        # NOUN + NOUN + NOUN → last is head, "head de mod1 mod2"
        if is_noun(w0) and is_noun(w2):
            n = WORD_DICT.get(w2, words[2])
            m1 = WORD_DICT.get(w0, words[0])
            m2 = WORD_DICT.get(w1, words[1])
            return f"{n} de {m1} {m2}"

        # ADJ + X + NOUN → NOUN ADJ de X
        if is_adjective(w0) and is_noun(w2):
            n = WORD_DICT.get(w2, words[2])
            adj = WORD_DICT.get(w0, words[0])
            adj = agree_adjective(adj, n)
            mid = WORD_DICT.get(w1, words[1]) if w1 in WORD_DICT else words[1]
            return f"{n} {adj} de {mid}"

        # NOUN + ADJ + NOUN → NOUN2 de NOUN1 ADJ (e.g. "dragon scale boots")
        if is_noun(w0) and is_adjective(w1) and is_noun(w2):
            n = WORD_DICT.get(w2, words[2])
            mod = WORD_DICT.get(w0, words[0])
            adj = WORD_DICT.get(w1, words[1])
            return f"{n} de {mod} {adj}"

        # X + X + known_noun → noun de X X
        if is_noun(w2) and w2 in WORD_DICT:
            n = WORD_DICT[w2]
            p0 = WORD_DICT.get(w0, words[0]) if w0 in WORD_DICT else words[0]
            p1 = WORD_DICT.get(w1, words[1]) if w1 in WORD_DICT else words[1]
            return f"{n} de {p0} {p1}"

        # known_noun + X + X → noun de X X
        if is_noun(w0) and w0 in WORD_DICT:
            n = WORD_DICT[w0]
            p1 = WORD_DICT.get(w1, words[1]) if w1 in WORD_DICT else words[1]
            p2 = WORD_DICT.get(w2, words[2]) if w2 in WORD_DICT else words[2]
            return f"{n} de {p1} {p2}"

    # --- General fallback: translate known words, keep order ---
    translated_words = []
    adjectives = []
    nouns = []

    for word in words:
        w_lower = word.lower()
        if w_lower in ("a", "an", "the"):
            continue
        elif w_lower in WORD_DICT and WORD_DICT[w_lower]:
            translated_words.append(WORD_DICT[w_lower])
        else:
            translated_words.append(word)

    return " ".join(translated_words)


def translate_item_name(name):
    """
    Główna funkcja tłumaczenia nazwy przedmiotu.
    Zwraca przetłumaczoną nazwę.
    """
    if not name:
        return name

    name_stripped = name.strip()
    name_lower = name_stripped.lower()

    # 1. Sprawdź exact match
    if name_lower in EXACT_TRANSLATIONS:
        return EXACT_TRANSLATIONS[name_lower]

    # 2. Sprawdź wzorce regex
    pattern_result = translate_pattern(name_lower)
    if pattern_result:
        return pattern_result

    # 3. Spróbuj tłumaczenia złożonego
    compound_result = translate_compound(name_stripped)
    if compound_result.lower() != name_lower:
        return compound_result

    # 4. Fallback - zwróć oryginał (bez [ES])
    return name_stripped


